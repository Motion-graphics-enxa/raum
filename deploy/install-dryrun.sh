#!/usr/bin/env bash
# F-03 proof: install.sh --dry-run transcripts for the two hardware profiles, from any machine.
#
#   deploy/install-dryrun.sh        -> deploy/install-dryrun-spark.txt, deploy/install-dryrun-lite.txt
#
# spark: a fake `nvidia-smi` on PATH answers like the GX10 ("NVIDIA GB10, [N/A]": unified memory has
#        no memory.total), with RAUM_FAKE_OS=Linux RAUM_FAKE_ARCH=aarch64 RAUM_FAKE_MEM_GB=121.
#        Two runs: --user-space (the shared GX10, the documented path) and the dedicated-box layout.
# lite:  this machine as it is (an 8 GB M2 Mac detects as lite).
# Read-only probes in the transcripts (installed commands, services on :11434 :7880 :8081) answer for
# the machine that ran this script. $HOME is shown as ~ and the repo as <repo>.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
FAKE="$(mktemp -d)"
trap 'rm -rf "$FAKE"' EXIT
cat > "$FAKE/nvidia-smi" <<'EOF'
#!/bin/sh
# fake GX10 nvidia-smi (install-dryrun.sh)
case "$*" in
  *--query-gpu=name,memory.total*) echo "NVIDIA GB10, [N/A]" ;;
  *) echo "NVIDIA-SMI 580.95.05   Driver Version: 580.95.05   CUDA Version: 13.0"; echo "GPU 0: NVIDIA GB10" ;;
esac
EOF
chmod +x "$FAKE/nvidia-smi"

clean() { sed -e "s|$ROOT|<repo>|g" -e "s|$HOME|~|g" -e "s|-o $(id -un) |-o <user> |g" -e "s|$(id -un):$(id -gn)|<user>:<group>|g"; }
header() {
  echo "# $1"
  echo "# generated by deploy/install-dryrun.sh on $(uname -s) $(uname -m), $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "# \$ $2"
  echo
}

{
  header "install.sh dry run, profile spark, shared GX10 (documented path: user space, deploy/box.sh)" \
    "PATH=<fake nvidia-smi>:\$PATH RAUM_FAKE_OS=Linux RAUM_FAKE_ARCH=aarch64 RAUM_FAKE_MEM_GB=121 ./install.sh --user-space --dry-run"
  PATH="$FAKE:$PATH" RAUM_FAKE_OS=Linux RAUM_FAKE_ARCH=aarch64 RAUM_FAKE_MEM_GB=121 \
    ./install.sh --user-space --dry-run </dev/null 2>&1 | clean
  echo
  echo
  header "install.sh dry run, profile spark, dedicated box (root, systemd, /opt/raum)" \
    "PATH=<fake nvidia-smi>:\$PATH RAUM_FAKE_OS=Linux RAUM_FAKE_ARCH=aarch64 RAUM_FAKE_MEM_GB=121 ./install.sh --dry-run"
  PATH="$FAKE:$PATH" RAUM_FAKE_OS=Linux RAUM_FAKE_ARCH=aarch64 RAUM_FAKE_MEM_GB=121 \
    ./install.sh --dry-run </dev/null 2>&1 | clean
} > deploy/install-dryrun-spark.txt

{
  header "install.sh dry run, profile lite (this machine as detected)" "./install.sh --dry-run"
  ./install.sh --dry-run </dev/null 2>&1 | clean
} > deploy/install-dryrun-lite.txt

grep -m1 '^  profile' deploy/install-dryrun-spark.txt
grep -m1 '^  profile' deploy/install-dryrun-lite.txt
echo "wrote deploy/install-dryrun-spark.txt deploy/install-dryrun-lite.txt"
