export function primaryLang(tag: string | undefined | null): string {
  return (tag || "en").toLowerCase().split(/[-_]/)[0] || "en";
}

export function langName(code: string, inLang?: string): string {
  try {
    const n = new Intl.DisplayNames([inLang || code], { type: "language" }).of(code);
    if (n && n !== code) return n.charAt(0).toLocaleUpperCase(inLang || code) + n.slice(1);
  } catch {
    /* unsupported */
  }
  return code.toUpperCase();
}

